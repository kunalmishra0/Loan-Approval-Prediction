"""Streamlit interface for Loan Approval Prediction."""

from __future__ import annotations

import logging
import sys
from pathlib import Path
from typing import Any

import pandas as pd
import streamlit as st

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.predict import load_metadata as load_model_metadata
from src.predict import load_pipeline, predict


logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s - %(levelname)s - %(message)s",
)
logger = logging.getLogger(__name__)


DISCLAIMER = (
    "This prediction is generated by a machine learning model for educational "
    "purposes only and should not be used for actual financial decisions."
)


@st.cache_resource(show_spinner=False)
def get_pipeline() -> Any:
    """Load and cache the trained prediction pipeline via predict.py."""
    return load_pipeline()


@st.cache_data(show_spinner=False)
def load_metadata() -> dict[str, Any]:
    """Load and cache model metadata via predict.py."""
    return load_model_metadata()


def _format_metric(value: Any) -> str:
    """Format numeric model metrics for display."""
    if isinstance(value, (float, int)):
        return f"{value:.3f}"

    return "Not available"


def render_sidebar(metadata: dict[str, Any]) -> None:
    """Render project and model information in the sidebar."""
    st.sidebar.header("Project Overview")
    st.sidebar.write(
        "Loan Approval Prediction system using a saved sklearn pipeline "
        "with preprocessing and classifier inference handled by `src.predict`."
    )

    st.sidebar.header("Model Information")
    st.sidebar.write(
        f"Best model: **{metadata.get('best_algorithm', 'Not available')}**"
    )

    st.sidebar.subheader("Performance Metrics")
    st.sidebar.metric("Accuracy", _format_metric(metadata.get("accuracy")))
    st.sidebar.metric("Precision", _format_metric(metadata.get("precision")))
    st.sidebar.metric("Recall", _format_metric(metadata.get("recall")))
    st.sidebar.metric("F1 Score", _format_metric(metadata.get("f1")))
    st.sidebar.metric("ROC AUC", _format_metric(metadata.get("roc_auc")))

    st.sidebar.header("Author")
    st.sidebar.write("Kunal Mishra")


def collect_user_input() -> dict[str, Any] | None:
    """Collect and validate applicant details from the main form."""
    with st.form("loan_prediction_form"):
        col_left, col_right = st.columns(2)

        with col_left:
            gender = st.selectbox("Gender", ["Male", "Female"])
            married = st.selectbox("Married", ["Yes", "No"])
            dependents = st.selectbox("Dependents", ["0", "1", "2", "3+"])
            education = st.selectbox(
                "Education",
                ["Graduate", "Not Graduate"],
            )
            self_employed = st.selectbox("Self Employed", ["No", "Yes"])
            property_area = st.selectbox(
                "Property Area",
                ["Urban", "Semiurban", "Rural"],
            )

        with col_right:
            applicant_income = st.number_input(
                "Applicant Income",
                min_value=0,
                value=5000,
                step=500,
            )
            coapplicant_income = st.number_input(
                "Coapplicant Income",
                min_value=0.0,
                value=0.0,
                step=500.0,
            )
            loan_amount = st.number_input(
                "Loan Amount",
                min_value=0.0,
                value=150.0,
                step=10.0,
            )
            loan_amount_term = st.selectbox(
                "Loan Amount Term",
                [12.0, 36.0, 60.0, 84.0, 120.0, 180.0, 240.0, 300.0, 360.0],
                index=8,
            )
            credit_history = st.selectbox(
                "Credit History",
                [1.0, 0.0],
                format_func=lambda value: "Good" if value == 1.0 else "Poor",
            )

        submitted = st.form_submit_button("Predict")

    if not submitted:
        return None

    if applicant_income < 0 or coapplicant_income < 0:
        st.error("Income values cannot be negative.")
        return None

    if loan_amount < 0:
        st.error("Loan amount cannot be negative.")
        return None

    if loan_amount_term <= 0:
        st.error("Loan amount term must be greater than zero.")
        return None

    return {
        "Gender": gender,
        "Married": married,
        "Dependents": dependents,
        "Education": education,
        "Self_Employed": self_employed,
        "ApplicantIncome": applicant_income,
        "CoapplicantIncome": coapplicant_income,
        "LoanAmount": loan_amount,
        "Loan_Amount_Term": loan_amount_term,
        "Credit_History": credit_history,
        "Property_Area": property_area,
    }


def display_prediction(result: pd.Series) -> None:
    """Display prediction output and interpretation."""
    prediction_label = str(result["prediction"])
    probability = result.get("probability")
    confidence = result.get("confidence")

    st.subheader("Prediction Result")

    if prediction_label == "Loan Approved":
        st.success("Loan Approved")
        st.write(
            "The model predicts that this applicant is likely to be approved "
            "based on the submitted profile."
        )
    else:
        st.error("Loan Rejected")
        st.write(
            "The model predicts that this applicant is unlikely to be approved "
            "based on the submitted profile."
        )

    metric_col_1, metric_col_2 = st.columns(2)
    metric_col_1.metric(
        "Approval Probability",
        f"{probability:.1%}" if isinstance(probability, float) else "N/A",
    )
    metric_col_2.metric(
        "Confidence",
        f"{confidence:.1%}" if isinstance(confidence, float) else "N/A",
    )

    st.info(DISCLAIMER)


def main() -> None:
    """Render the Streamlit application."""
    st.set_page_config(
        page_title="Loan Approval Prediction",
        layout="wide",
    )

    st.title("Loan Approval Prediction")
    st.write(
        "Enter applicant and loan details to estimate whether a loan is likely "
        "to be approved. The app uses the trained project prediction module, "
        "which loads the saved preprocessing and classification pipeline."
    )

    try:
        pipeline = get_pipeline()
        metadata = load_metadata()
    except Exception as exc:
        logger.exception("Failed to initialize Streamlit app: %s", exc)
        st.error(
            "The trained model could not be loaded. Please train the model "
            "first with `python -m src.train`."
        )
        return

    render_sidebar(metadata)
    user_input = collect_user_input()

    if user_input is None:
        st.info("Fill in the application details and click Predict.")
        st.info(DISCLAIMER)
        return

    try:
        prediction_result = predict(user_input, pipeline, metadata).iloc[0]
        display_prediction(prediction_result)
    except Exception as exc:
        logger.exception("Prediction failed: %s", exc)
        st.error(
            "Prediction failed. Please check the input values and try again."
        )


if __name__ == "__main__":
    main()

